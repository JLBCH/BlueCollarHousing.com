// Generates supabase/migrations/0002_seed.sql from the seed JSON, so the
// database seed and the app's fallback seed never drift. Run:
//   node scripts/gen-seed-sql.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const seed = JSON.parse(
  readFileSync(join(here, "../src/lib/listings/seed.json"), "utf8"),
);

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const txtArr = (arr) =>
  `array[${arr.map((v) => q(v)).join(", ")}]::text[]`;
const val = (v) => (v === null || v === undefined ? "NULL" : v);

const COLS = [
  "slug", "status", "title", "property_type", "bedrooms", "bathrooms",
  "price_month", "lease_length", "description", "nearby_projects", "amenities",
  "utilities_included", "pet_policy", "city", "state", "public_area", "lat",
  "lng", "contact_phone", "show_phone", "contact_email", "show_email",
  "allow_contact_form", "photos",
];

const row = (l) =>
  "  (" +
  [
    q(l.slug),
    q(l.status),
    q(l.title),
    q(l.propertyType),
    l.bedrooms,
    l.bathrooms,
    l.priceMonth,
    q(l.leaseLength),
    q(l.description),
    q(l.nearbyProjects),
    txtArr(l.amenities),
    l.utilitiesIncluded,
    q(l.petPolicy),
    q(l.city),
    q(l.state),
    q(l.publicArea),
    l.lat,
    l.lng,
    l.contactPhone === null ? "NULL" : q(l.contactPhone),
    l.showPhone,
    l.contactEmail === null ? "NULL" : q(l.contactEmail),
    l.showEmail,
    l.allowContactForm,
    txtArr(l.photos),
  ].map(val).join(", ") +
  ")";

const sql = `-- BlueCollarHousing · 0002_seed (generated by scripts/gen-seed-sql.mjs, do not edit by hand)
-- ${seed.length} sample listings. Safe to re-run (on conflict by slug, do nothing).

insert into public.listings (${COLS.join(", ")})
values
${seed.map(row).join(",\n")}
on conflict (slug) do nothing;
`;

const out = join(here, "../supabase/migrations/20260610090002_seed.sql");
writeFileSync(out, sql);
console.log(`Wrote ${out} (${seed.length} listings)`);
